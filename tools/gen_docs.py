"""Generate the command and language-model documentation from source."""

import argparse
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from crusader.commands import COMMANDS  # noqa: E402


def functions(path):
    tree = ast.parse(path.read_text())
    return {node.name: node for node in ast.walk(tree) if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))}


def expression(node):
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return repr(node.value)
    return ast.unparse(node) + " (dynamic expression)"


def refusals(path):
    result = {}
    calls = {}
    for name, fn in functions(path).items():
        found, deps = [], set()
        for node in ast.walk(fn):
            if (
                isinstance(node, ast.Raise)
                and isinstance(node.exc, ast.Call)
                and (
                    isinstance(node.exc.func, ast.Name)
                    and node.exc.func.id in {"RealGameError", "ValueError"}
                    and node.exc.args
                )
            ):
                found.append((node.lineno, expression(node.exc.args[0])))
            if (
                isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute)
                and isinstance(node.func.value, ast.Name)
                and node.func.value.id == "self"
            ):
                deps.add(node.func.attr)
                if node.func.attr == "_check" and len(node.args) >= 2:
                    found.append((node.lineno, expression(node.args[1])))
        result[name] = found
        calls[name] = deps
    return result, calls


def reachable(name, found, calls):
    pending, seen, items = [name], set(), set()
    while pending:
        n = pending.pop()
        if n in seen:
            continue
        seen.add(n)
        items.update(found.get(n, []))
        pending.extend(calls.get(n, set()) - seen)
    return sorted(items)


def code(text):
    return "`" + str(text).replace("`", "\\`").replace("|", "\\|") + "`"


def example(param):
    name, typ = param["name"], param["type"]
    values = {
        "building": '"woodcutter"',
        "unit": '"archer"',
        "good": '"wood"',
        "level": "1",
        "qty": "5",
        "stance": '"defensive"',
        "weapon": '"bows"',
        "food": '"bread"',
        "engine": '"catapult"',
        "order": '"defend"',
        "page": '"economy"',
        "points": "[(10, 10)]",
    }
    if name in values:
        return values[name]
    if "bool" in typ:
        return "True"
    if "Iterable" in typ:
        return "[1]"
    if "str" in typ:
        return '"example"'
    return "1"


def command_sections():
    """Read the command prose, omitting links back to the generated reference."""
    sections = {}
    heading = re.compile(r"^## `([^`]+)`\s*$", re.MULTILINE)
    for path in sorted((ROOT / "docs/commands").glob("*.md")):
        text = path.read_text()
        matches = list(heading.finditer(text))
        for index, match in enumerate(matches):
            name = match.group(1)
            if name in sections:
                raise ValueError(f"Duplicate command section: {name}")
            end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
            body = text[match.end() : end].strip()
            body = re.sub(r" ?\[API reference\]\(\.\./api\.md#[^)]*\)\.?", "", body)

            def rebase_link(match, source=path):
                target = match.group(2)
                if target.startswith(("#", "/")) or re.match(r"[a-zA-Z][a-zA-Z0-9+.-]*:", target):
                    return match.group(0)
                location, separator, fragment = target.partition("#")
                rebased = (source.parent / location).resolve().relative_to((ROOT / "docs").resolve())
                return f"{match.group(1)}{rebased.as_posix()}{separator}{fragment})"

            body = re.sub(r"(\[[^\]]*\]\()([^ )]+)\)", rebase_link, body)
            sections[name] = body.strip()
    missing = set(COMMANDS) - sections.keys()
    if missing:
        raise ValueError(f"Missing command sections: {', '.join(sorted(missing))}")
    return sections


def generate():
    sections = command_sections()
    client = functions(ROOT / "src/crusader/__init__.py")
    game, calls = refusals(ROOT / "src/crusader/bridge/game.py")
    server, _server_calls = refusals(ROOT / "src/crusader/bridge/server.py")
    api = [
        "# API reference",
        "",
        "Generated from the client and command metadata. Examples are illustrative; "
        "game state and IDs determine whether commands succeed.",
        "",
    ]
    errors = [
        "# Refusals and errors",
        "",
        "Generated by static AST inspection. Dynamic expressions are shown as Python source, not literal messages. "
        "Helper-method refusals are attributed through static self-call reachability; conditional paths may not "
        "apply to every invocation. Server validations may apply to multiple commands.",
        "",
    ]
    for name, spec in COMMANDS.items():
        fn = client[name]
        signature = f"{name}({ast.unparse(fn.args)})"
        if fn.returns:
            signature += " -> " + ast.unparse(fn.returns)
        entries = reachable(spec["command"], game, calls)
        api += [
            f'<a id="{name}"></a>',
            f"## {name}",
            "",
            sections[name],
            "",
            "```python",
            signature,
            "```",
            "",
            "| Parameter | Type | Default | Constraints |",
            "| --- | --- | --- | --- |",
        ]
        for param in spec["params"]:
            default = repr(param["default"]) if "default" in param else "required"
            constraints = param.get("constraints", "—").replace("|", "\\|")
            api.append(f"| {code(param['name'])} | {code(param['type'])} | {code(default)} | {constraints} |")
        if not spec["params"]:
            api.append("| — | — | — | — |")
        api += [
            "",
            f"**Returns:** {code(spec['return_type'])}",
            "",
            f"**Refusals:** See [errors for {name}](reference/errors.md#{name}); "
            "bridge-wide validation can also reject a request.",
            "",
        ]
        if not re.search(r"^```python\s*$", sections[name], re.MULTILINE):
            api += [
                "```python",
                f"game.{name}({', '.join(p['name'] + '=' + example(p) for p in spec['params'] if 'default' not in p)})",
                "```",
                "",
            ]
        errors += [f'<a id="{name}"></a>', f"## {name}", ""]
        errors += [f"- {code(msg)} (game.py:{line})" for line, msg in entries] or [
            "- No game refusal found by static self-call inspection."
        ]
        errors.append("")
    errors += [
        "## Bridge-wide and other source refusals",
        "",
        "These are listed by enclosing function because dispatch and shared helpers can serve several commands. "
        "This includes setup and non-command errors.",
        "",
    ]
    for source, data in (("game.py", game), ("server.py", server)):
        for name, entries in sorted(data.items()):
            for line, msg in sorted(entries):
                errors.append(f"- {source}:{line} / {code(name)}: {code(msg)}")
    errors.append("")
    outputs = {"docs/api.md": "\n".join(api), "docs/reference/errors.md": "\n".join(errors)}
    pages = sorted(set(p.relative_to(ROOT).as_posix() for p in (ROOT / "docs").rglob("*.md")) | set(outputs))
    index = ["# Crusader SDK", "", "> Python SDK and bridge for Stronghold Crusader.", "", "## Documentation", ""]
    index += [f"- [{p.removeprefix('docs/').removesuffix('.md')}]({p}): Documentation page." for p in pages]
    outputs["llms.txt"] = "\n".join(index) + "\n"
    outputs["llms-full.txt"] = (
        "# Crusader SDK — complete documentation\n\n"
        + "\n\n".join(
            f"<!-- {p} -->\n\n" + outputs.get(p, (ROOT / p).read_text() if (ROOT / p).exists() else "").rstrip()
            for p in pages
        )
        + "\n"
    )
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    drift = []
    for path, content in generate().items():
        file = ROOT / path
        if not file.exists() or file.read_text() != content:
            drift.append(path)
            if not args.check:
                file.parent.mkdir(parents=True, exist_ok=True)
                file.write_text(content)
    if args.check and drift:
        print("Generated documentation is out of date: " + ", ".join(drift), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
